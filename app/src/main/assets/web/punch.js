/* Punch-in FX: eight pads on the Performance page. An effect is active only while the pad is held.
   - HAT ROLL / SNARE ROLL / STUTTER are generated by this page (MIDI notes / CC11) and lock to the pattern's 16th grid.
   - LOW-PASS / HIGH-PASS / DELAY THROW / REVERB WASH change JD-Xi parameters with SysEx (DT1). The original values are
     read from the synth first and put back on release.
   - PITCH DIVE bends the pitch of the synth parts down and snaps back to centre on release. */
const $=id=>document.getElementById(id);
const api=window.JDXiPerformance;
const host=$('perfpunch');
if(!host||!api)return;
const status=t=>{const s=$('perfstatus');if(s)s.textContent=t};
const clamp=(v,a,b)=>Math.max(a,Math.min(b,v));
const epoch=()=>window.JDXiPerfEpoch?window.JDXiPerfEpoch():0;
const SYNTH_CH=[0,1,2];            /* Digital 1, Digital 2, Analog */
const ALL_CH=[0,1,2,9];            /* + Drums (MIDI channel 10) */

/* ---------- timing ---------- */
function bpm(){
 const s=window.JDXiPerfState?window.JDXiPerfState():null;
 const v=s&&s.running?s.bpm:+$('perfbpm').value;
 return clamp(Number.isFinite(v)&&v>0?v:120,40,240);
}
/* time (performance.now() scale) of the next grid line; `sub` = grid size in beats (0.25 = 1/16 note) */
function gridStart(sub){
 const now=performance.now(),step=60000/bpm()*sub,s=window.JDXiPerfState?window.JDXiPerfState():null;
 if(s&&s.running&&s.bars){
  const g=s.frac*s.bars*4/sub,f=g-Math.floor(g);
  return now+(f<0.03?0:(1-f)*step);
 }
 return now+4;
}
/* calls fn(time,n,stepMs) for every grid step while running; returns a stop function */
function repeater(sub,fn){
 let n=0,t=gridStart(sub);
 const pump=()=>{
  const now=performance.now(),step=60000/bpm()*sub;
  while(t<now+60){fn(t,n++,step);t+=step}
 };
 const timer=setInterval(pump,15);
 pump();
 return()=>clearInterval(timer);
}

/* ---------- parameter snapshot (read from the JD-Xi, restore later) ---------- */
const stamp=new Map();             /* address -> {t,epoch} of our last fresh read */
function snapshot(addrs,blocks,cb){
 const rb=api.readback(),now=performance.now(),ep=epoch();
 if(addrs.every(a=>rb.has(a))&&(warmedEpoch===ep||addrs.every(a=>{const st=stamp.get(a);return st&&st.epoch===ep&&now-st.t<4000}))){cb(true);return}
 if(!api.connected()||!api.hasSysex()||!api.hasInput()){
  status('This effect changes the sound, so it needs SysEx and a MIDI input (Info → MIDI connection).');cb(false);return;
 }
 addrs.forEach(a=>rb.delete(a));
 const GAP=55;                                    /* the JD-Xi answers one request at a time: do not flood it */
 const ask=list=>list.forEach(([a,len],i)=>setTimeout(()=>api.rq1(a,len),i*GAP));
 const missing=()=>blocks.filter(([a,len])=>addrs.some(x=>x>=a&&x<a+len&&!rb.has(x)));
 status('Reading the sound from the JD-Xi…');
 ask(blocks);
 const t0=performance.now(),limit=700+blocks.length*GAP*2;let retried=false;
 const poll=setInterval(()=>{
  const miss=missing();
  if(!miss.length){
   clearInterval(poll);const t=performance.now(),e2=epoch();
   addrs.forEach(a=>stamp.set(a,{t,epoch:e2}));cb(true);return;
  }
  const el=performance.now()-t0;
  if(!retried&&el>300+blocks.length*GAP){retried=true;ask(miss)}
  if(el>limit){
   clearInterval(poll);
   status('No reply from the JD-Xi for '+miss.length+' of '+blocks.length+' blocks (first: '+miss[0][0].toString(16).toUpperCase().padStart(8,'0')+'). Check the MIDI input (Info → MIDI connection).');
   cb(false);
  }
 },20);
}
const send=(a,v)=>api.dt1(a,[clamp(Math.round(v),0,127)]);

/* Applies items [{a,orig,to,from?,ramp?}] and returns {release()}.
   ramp items glide to `to` (from `from`, or from their original value); the others jump. */
function engage(items,ep0){
 const ramps=items.filter(x=>x.ramp),jumps=items.filter(x=>!x.ramp),N=5;
 ramps.forEach(x=>{x.cur=x.from!=null?x.from:x.orig;if(x.from!=null)send(x.a,x.cur)});   /* cutoff first, then switch the filter type */
 jumps.forEach(x=>send(x.a,x.to));
 let iv=null,k=0;
 if(ramps.length)iv=setInterval(()=>{
  k++;
  ramps.forEach(x=>{const s0=x.from!=null?x.from:x.orig;x.cur=s0+(x.to-s0)*k/N;send(x.a,x.cur)});
  if(k>=N){clearInterval(iv);iv=null}
 },22);
 return{release(){
  if(iv){clearInterval(iv);iv=null}
  if(epoch()!==ep0)return;      /* the JD-Xi switched program meanwhile: its new sound must not be overwritten */
  const soft=ramps.filter(x=>x.from==null),hard=ramps.filter(x=>x.from!=null);
  if(!soft.length){hard.forEach(x=>send(x.a,x.orig));jumps.forEach(x=>send(x.a,x.orig));return}
  hard.forEach(x=>send(x.a,x.orig));
  const c0=soft.map(x=>x.cur),M=4;let j=0;
  const back=()=>{
   j++;soft.forEach((x,n)=>send(x.a,c0[n]+(x.orig-c0[n])*j/M));
   if(j<M)setTimeout(back,20);else jumps.forEach(x=>send(x.a,x.orig));
  };
  back();
 }};
}
/* generic "change parameters while held" effect */
function paramEffect(addrs,blocks,plan,fallback){
 const MIN=0;                        /* effects stop on release, never at the next bar */
 return()=>{
  let held=true,eng=null,tOn=0,released=false;const ep0=epoch();
  const doRelease=()=>{if(!eng||released)return;released=true;eng.release()};
  const releaseSoon=()=>{const rem=MIN-(performance.now()-tOn);if(rem>0)setTimeout(doRelease,rem);else doRelease()};
  const begin=e=>{eng=e;tOn=performance.now();if(!held)releaseSoon()};
  snapshot(addrs,blocks,ok=>{
   // An asynchronous RQ1 must never trigger a punch after the user has released the pad.
   if(!held||epoch()!==ep0)return;
   if(!ok){if(fallback)begin(fallback());return}
   const rb=api.readback();
   const items=plan(rb).filter(x=>x.orig!==undefined);
   if(!items.length){status('Could not read the current sound from the JD-Xi.');if(fallback)begin(fallback());return}
   begin(engage(items,ep0));
  });
  return{stop(){held=false;if(eng)releaseSoon()}};
 };
}

/* ---------- effect definitions ---------- */
const DIG=[0x19010000,0x19210000].flatMap(b=>[0,1,2].map(p=>b+0x2000+0x100*p));  /* digital partial blocks */
const ANA=0x19420000;
const FILTER_BLOCKS=[...DIG.map(a=>[a,0x3d]),[ANA,0x40]];
const FILTER_ADDRS=[...DIG.flatMap(b=>[b+10,b+12]),ANA+32,ANA+33];
const PARTS=[0x18002000,0x18002100,0x18002200,0x18002300];
const PART_BLOCKS=PARTS.map(a=>[a,0x4c]);
const LPF_TYPES=[1,5,6,7];
/* No read-back needed: Control Change 74 (Part Cutoff Offset, 64 = unchanged) closes the filter, and 64 restores it. */
function lowPassCC(){
 let k=0;const N=5;
 const iv=setInterval(()=>{k++;SYNTH_CH.forEach(ch=>api.send([0xb0|ch,74,Math.round(64-64*k/N)]));if(k>=N)clearInterval(iv)},22);
 status('Low-pass: cutoff offset (CC 74) on parts 1–3.');
 return{stop(){clearInterval(iv);SYNTH_CH.forEach(ch=>api.send([0xb0|ch,74,64]))}};
}

/* Direct CC is sent at pointer-down, independently of pattern or RQ1 timing.
   The last known part levels are used for restoration. Missing values default
   to zero; this is signalled so a user can first read the program. */
function sendLevelCC(cc,offset,label){
 const rb=api.readback(),ep0=epoch();
 const restore=PARTS.map((a,i)=>({ch:ALL_CH[i],v:rb.get(a+offset)}));
 const missing=restore.some(x=>x.v===undefined);
 restore.forEach(x=>api.send([0xb0|x.ch,cc,127]));
 if(missing)status(label+': immediate CC sent; unknown original sends restore to 0. Read the program first for exact restore.');
 let stopped=false;
 return{stop(){if(stopped)return;stopped=true;if(epoch()!==ep0)return;
  restore.forEach(x=>api.send([0xb0|x.ch,cc,x.v===undefined?0:x.v]));
 }};
}
/* Warm the readback cache without blocking a pad. A program change invalidates it. */
let warmedEpoch=-1,warming=false;
function warmPunch(){
 if(warming||!api.connected()||!api.hasInput()||!api.hasSysex())return;
 const ep=epoch();if(ep===warmedEpoch)return;
 warming=true;
 // Never reuse an old program's sound as the restoration baseline.
 const rb=api.readback();
 [...FILTER_ADDRS,...PARTS.flatMap(a=>[a+0x0f,a+0x2b,a+0x2c])].forEach(a=>rb.delete(a));
 const blocks=[...FILTER_BLOCKS,...PART_BLOCKS];
 let i=0;
 const tick=()=>{
  if(epoch()!==ep||!api.connected()){warming=false;return}
  if(i>=blocks.length){warmedEpoch=ep;warming=false;return}
  const [a,len]=blocks[i++];api.rq1(a,len);
  setTimeout(tick,75);
 };
 tick();
}
setTimeout(warmPunch,1700);
setInterval(warmPunch,2500);
/* Eight additional live drum/gate variations. Unlike grid-quantized legacy pads,
   these begin on pointer-down, with no wait for a pattern/bar boundary. Timers and
   pending note-offs are cancelled on release to avoid late ghost triggers. */
function liveDrumRoll(note,division,velocities,opts={}){
 return ()=>{
  let active=true,n=0,next=null;
  const offTimers=new Set();
  const sendNoteOff=()=>api.send([0x89,note,0]);
  const tick=()=>{
   if(!active)return;
   const v=typeof velocities==='function'?velocities(n):velocities[n%velocities.length];
   const interval=60000/bpm()*division;
   api.send([0x99,note,clamp(Math.round(v),1,127)]);
   // Hold short enough for repeated notes. No scheduled notes remain after release.
   const off=setTimeout(()=>{offTimers.delete(off);sendNoteOff()},Math.max(15,Math.min(interval*.48,115)));
   offTimers.add(off);
   n++;
   next=setTimeout(tick,Math.max(20,interval));
  };
  tick(); // first strike is immediate
  return {stop(){
   if(!active)return;
   active=false;clearTimeout(next);
   offTimers.forEach(clearTimeout);offTimers.clear();sendNoteOff();
  }};
 };
}
function quickGate32(){
 return ()=>{
  const channels=ALL_CH;
  const sendGate=v=>channels.forEach(ch=>api.send([0xb0|ch,11,v]));
  let active=true,timer=null,n=0;
  const tick=()=>{
   if(!active)return;
   sendGate(n++%2?127:0);
   timer=setTimeout(tick,Math.max(20,60000/bpm()*.125));
  };
  tick();
  return {stop(){if(!active)return;active=false;clearTimeout(timer);sendGate(127)}};
 };
}
